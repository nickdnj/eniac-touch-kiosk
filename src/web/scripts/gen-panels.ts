// Regenerates src/web/panels/*.svg from app/panels/art.ts (dev-only; Node).
//   npm run gen:panels          write the files
//   node scripts/gen-panels.ts --check   exit 1 if any file is stale
// tests/web/panels.test.ts runs the --check logic so the files never drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { allPanels } from "../app/panels/art.ts";

const outDir = join(dirname(fileURLToPath(import.meta.url)), "..", "panels");

export function expectedFiles(): Map<string, string> {
  const m = new Map<string, string>();
  for (const p of allPanels(true)) {
    const header = `<?xml version="1.0" encoding="UTF-8"?>\n<!-- GENERATED by src/web/scripts/gen-panels.ts from app/panels/art.ts. Do not edit; see panels/README.md. -->\n`;
    m.set(`${p.name}.svg`, header + p.markup.replace(/></g, ">\n<") + "\n");
  }
  return m;
}

export function staleFiles(): string[] {
  const stale: string[] = [];
  for (const [name, body] of expectedFiles()) {
    let cur = "";
    try {
      cur = readFileSync(join(outDir, name), "utf8");
    } catch {}
    if (cur !== body) stale.push(name);
  }
  return stale;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  if (process.argv.includes("--check")) {
    const s = staleFiles();
    if (s.length) {
      console.error("stale panels (run npm run gen:panels):", s.join(", "));
      process.exit(1);
    }
    console.log("panels up to date");
  } else {
    for (const [name, body] of expectedFiles()) writeFileSync(join(outDir, name), body);
    console.log(`wrote ${expectedFiles().size} panels to ${outDir}`);
  }
}
